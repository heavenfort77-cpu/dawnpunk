# Packs art/models/*.glb into src/modeldata.js (base64), so the game stays one HTML file. Usage: python3 tools/makemodels.py
import base64, os
D = os.path.join(os.path.dirname(__file__), '..', 'art', 'models'); out = []
for f in sorted(os.listdir(D)):
    if f.endswith('.glb'): b = open(os.path.join(D, f), 'rb').read(); out.append("  %s: '%s'" % (f[:-4], base64.b64encode(b).decode())); print(f, round(len(b) / 1024), 'KB')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'modeldata.js'), 'w').write('// generated by tools/makemodels.py from art/models/*.glb\nexport const MODELS = {\n' + ',\n'.join(out) + '\n};\n')
