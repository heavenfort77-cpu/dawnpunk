# Shrinks the music originals (art/music_src/*.mp3, never changed) to small MP3s in art/music/ and packs them into src/musicdata.js.
# Change KBPS / RATE here and re-run: python3 tools/makemusic.py
import subprocess, base64, os
KBPS, RATE = 48, 32000
MAP = {'base': 'where_the_roots_breathe', 'day': 'ivy_on_the_glass', 'night': 'the_green_perimeter'}  # which track plays where
out = []
for key, name in MAP.items():
    src, dst = f'art/music_src/{name}.mp3', f'art/music/{name}.mp3'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-ac', '2', '-ar', str(RATE), '-b:a', f'{KBPS}k', '-joint_stereo', '1', '-map_metadata', '-1', dst], check=True)
    out.append(f"  {key}: 'music/{name}.mp3',"); print(key, name, os.path.getsize(dst) // 1024, 'KB')
open('src/musicdata.js', 'w').write('// generated by tools/makemusic.py. Paths beside index.html; build.mjs also makes a single-file build with the music embedded.\nexport const MUSIC = {\n' + '\n'.join(out) + '\n};\n')
